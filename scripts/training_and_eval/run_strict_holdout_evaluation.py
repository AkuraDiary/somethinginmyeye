import os
import glob
import numpy as np
import pandas as pd
import tensorflow as tf
from tensorflow.keras.callbacks import EarlyStopping, ReduceLROnPlateau
from sklearn.metrics import confusion_matrix, roc_curve, auc, accuracy_score, recall_score, precision_score, f1_score
import matplotlib.pyplot as plt
import seaborn as sns

from universal_pipeline import load_and_scale_universal, extract_universal_features, MAX_TIMESTEPS, get_v0_data, get_v1_data, get_v2_data
from unified_evaluator import build_v0_baseline, build_v1_xai, build_v2_lstm

TRAIN_DIR = "datasets"
VAL_DIR = "val_datasets"
OUTPUT_DIR = "evaluation_results_holdout"
os.makedirs(OUTPUT_DIR, exist_ok=True)

def load_validation_data_with_train_scalers(val_dir, scaler_path="../models/feature_scalers.npz"):
    """
    CRITICAL: You CANNOT fit a new scaler on the validation data. 
    You must use the EXACT SAME scaling multipliers that were calculated on the training data.
    """
    try:
        scaler_data = np.load(scaler_path)
        feature_means = scaler_data['means']
        feature_stds = scaler_data['stds']
    except Exception as e:
        print(f"Error loading {scaler_path}. Scalers must be generated by the training data first.")
        raise e
        
    sequences = []
    latencies = []
    labels = []
    
    csv_files = glob.glob(os.path.join(val_dir, "*.csv"))
    if not csv_files:
        raise ValueError(f"No CSV files found in {val_dir}!")
        
    for file in csv_files:
        df = pd.read_csv(file)
        if len(df) == 0: continue
            
        latency_val = df["latency"].iloc[0] if "latency" in df.columns else 0
        filename = os.path.basename(file).lower()
        if "normal" in filename: label = 0
        elif "dyslexia" in filename or "dysgraphia" in filename: label = 1
        else: continue
            
        stroke_data = extract_universal_features(df)
        
        # Padding
        if len(stroke_data) > MAX_TIMESTEPS:
            stroke_data = stroke_data[:MAX_TIMESTEPS]
        else:
            padding = np.zeros((MAX_TIMESTEPS - len(stroke_data), 9))
            stroke_data = np.vstack((stroke_data, padding))
            
        sequences.append(stroke_data)
        latencies.append(latency_val)
        labels.append(label)

    # Convert to Numpy
    X_seq = np.array(sequences)
    X_lat = np.array(latencies)
    y = np.array(labels)
    
    # APPLY THE TRAINING SCALERS (No data leakage!)
    X_seq_clean = np.nan_to_num(X_seq, nan=0.0, posinf=0.0, neginf=0.0)
    X_seq_scaled = (X_seq_clean - feature_means) / feature_stds
    X_lat_scaled = X_lat / 1000.0
    
    print(f"✅ Successfully loaded and scaled {len(y)} VALIDATION samples.")
    return X_seq_scaled, X_lat_scaled, y

def process_predictions_holdout(model, X_test, y_test_raw):
    y_pred_probs = model.predict(X_test, verbose=0)
    if len(y_pred_probs.shape) == 3:
        y_pred_probs_flat = np.mean(y_pred_probs, axis=1).flatten()
    else:
        y_pred_probs_flat = y_pred_probs.flatten()
        
    y_pred_classes = (y_pred_probs_flat > 0.5).astype(int)
    
    if len(y_test_raw.shape) >= 2:
        y_true_flat = np.max(y_test_raw, axis=1).flatten()
    else:
        y_true_flat = y_test_raw.flatten()
        
    return y_true_flat, y_pred_probs_flat, y_pred_classes

def evaluate_strict_holdout():
    print("📁 1. Loading TRAINING Dataset...")
    X_train_seq_scaled, X_train_lat_scaled, y_train = load_and_scale_universal(TRAIN_DIR)
    print(f"📊 Training Data Size: {len(y_train)} samples")
    
    print("\n📁 2. Loading VALIDATION Dataset (Using strict training scalers)...")
    # This assumes load_and_scale_universal saved to ../models/feature_scalers.npz
    X_val_seq_scaled, X_val_lat_scaled, y_val = load_validation_data_with_train_scalers(VAL_DIR, scaler_path="../models/feature_scalers.npz")
    print(f"📊 Validation Data Size: {len(y_val)} samples")
    
    data_maps = [
        ("V0 (CNN Baseline)", build_v0_baseline, 
         get_v0_data(X_train_seq_scaled, y_train), get_v0_data(X_val_seq_scaled, y_val)),
         
        ("V1 (CNN + XAI)", build_v1_xai, 
         get_v1_data(X_train_seq_scaled, X_train_lat_scaled, y_train), 
         get_v1_data(X_val_seq_scaled, X_val_lat_scaled, y_val)),
         
        ("V2 (Bi-LSTM)", build_v2_lstm, 
         get_v2_data(X_train_seq_scaled, X_train_lat_scaled, y_train), 
         get_v2_data(X_val_seq_scaled, X_val_lat_scaled, y_val))
    ]
    
    roc_data = []
    
    for name, build_fn, (X_train_data, y_train_data), (X_val_data, y_val_data) in data_maps:
        print(f"\n🧠 Training and Evaluating {name} on Strict Hold-out Set...")
        
        model = build_fn()
        
        # --- TUNING CALLBACKS ---
        early_stop = EarlyStopping(monitor='val_loss', patience=12, restore_best_weights=True, verbose=1)
        reduce_lr = ReduceLROnPlateau(monitor='val_loss', factor=0.5, patience=5, min_lr=1e-6, verbose=1)
        
        # Train on Training Data, Validate on the True Holdout Data
        model.fit(X_train_data, y_train_data, epochs=100, batch_size=32, verbose=0, 
                  validation_data=(X_val_data, y_val_data), 
                  callbacks=[early_stop, reduce_lr])
        
        # Predict purely on Unseen Validation Data
        y_true, y_prob, y_class = process_predictions_holdout(model, X_val_data, y_val_data)
        
        # Calculate Metrics
        cm = confusion_matrix(y_true, y_class)
        acc = accuracy_score(y_true, y_class)
        recall = recall_score(y_true, y_class)
        prec = precision_score(y_true, y_class)
        f1 = f1_score(y_true, y_class)
        
        fpr, tpr, _ = roc_curve(y_true, y_prob)
        roc_auc = auc(fpr, tpr)
        roc_data.append((fpr, tpr, roc_auc, name))
        
        print(f"✅ {name} Hold-out Results:")
        print(f"   -> Accuracy: {acc*100:.2f}% | Recall: {recall*100:.2f}% | Precision: {prec*100:.2f}% | F1: {f1*100:.2f}% | AUC: {roc_auc:.4f}")
        
        # Save CM Image
        plt.figure(figsize=(6, 5), dpi=300)
        sns.heatmap(cm, annot=True, fmt='d', cmap='Blues', cbar=False,
                    annot_kws={"size": 18, "weight": "bold"},
                    xticklabels=['Typical', 'Atypical'],
                    yticklabels=['Typical', 'Atypical'])
        plt.title(f"{name} (Strict Hold-Out)\nConfusion Matrix", fontsize=14, fontweight='bold')
        plt.ylabel('Actual Classification', fontweight='bold')
        plt.xlabel('System Prediction', fontweight='bold')
        plt.tight_layout()
        safe_title = name.replace(" ", "_").replace("(", "").replace(")", "").replace("+", "plus")
        plt.savefig(os.path.join(OUTPUT_DIR, f"{safe_title}_Holdout_CM.png"), bbox_inches='tight')
        plt.close()
        
    # Plot Combined ROC
    plt.figure(figsize=(8, 6), dpi=300)
    colors = ['blue', 'green', 'darkorange']
    for (fpr, tpr, roc_auc, label), color in zip(roc_data, colors):
        plt.plot(fpr, tpr, color=color, lw=2.5, label=f'{label} (AUC = {roc_auc:.4f})')
        
    plt.plot([0, 1], [0, 1], color='gray', lw=2, linestyle='--', label='Random Guess')
    plt.xlim([0.0, 1.0])
    plt.ylim([0.0, 1.05])
    plt.xlabel('False Positive Rate', fontweight='bold')
    plt.ylabel('True Positive Rate', fontweight='bold')
    plt.title('Combined ROC-AUC (Strict Hold-Out Evaluation)', fontsize=14, fontweight='bold')
    plt.legend(loc="lower right")
    plt.grid(True, linestyle=':', alpha=0.6)
    plt.tight_layout()
    plt.savefig(os.path.join(OUTPUT_DIR, "Combined_Holdout_ROC_AUC.png"), bbox_inches='tight')
    plt.close()
    print(f"\n🎉 All Hold-Out evaluations complete! Images saved to {OUTPUT_DIR}/")

if __name__ == "__main__":
    evaluate_strict_holdout()
